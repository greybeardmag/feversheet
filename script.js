function buildRow(f, mgDose, drug, isEmpty) {
  const amtCls = drug === 'tylenol' ? 'tylenol-amt' : 'advil-amt';
  let amountStr = '—', unitStr = '';
  if (!isEmpty && mgDose !== null) {
    if (f.perUnit) {
      amountStr = formatTablets(mgDose / f.perUnit);
      unitStr = f.unitOut;
    } else {
      amountStr = formatVolume(mgDose / f.conc);
      unitStr = 'mL';
    }
  }
  const freq     = drug === 'tylenol' ? t('freq_tylenol') : t('freq_advil');
  const maxDose  = drug === 'tylenol' ? t('max_doses_tylenol') : t('max_doses_advil');
  const formName = t(f.nameKey);
  const noteText = f.noteKey ? t(f.noteKey) : '';

  return `<tr>
    <td>
      <div class="td-formulation">${formName}</div>
      <div class="td-conc">${f.concLabel}</div>
    </td>
    <td style="text-align:center">
      <div class="td-amount ${isEmpty ? 'pending' : amtCls}">${isEmpty ? '—' : amountStr}</div>
      <div class="td-unit">${isEmpty ? t('enter_weight') : unitStr}</div>
    </td>
    <td>
      <div class="td-freq">${freq}</div>
      <div class="td-freq-sub">${maxDose}</div>
    </td>
    <td>
      ${noteText ? `<span class="td-note-tag">${noteText}</span>` : '<span style="color:var(--rule);font-size:0.75rem;">—</span>'}
    </td>
  </tr>`;
}

